import { supabase } from "@/lib/supabase";

export const repairService = {
  async getRepairs(deviceId: string) {
    return await supabase
      .from("repairs")
      .select("*, repair_tickets(id, ticket_number, issued_at)")
      .eq("device_id", deviceId)
      .order("created_at", { ascending: false });
  },

  async getAllRepairs() {
    return await supabase
      .from("repairs")
      .select(
        "*, devices(brand, model, customers(full_name)), repair_tickets(id, ticket_number)"
      )
      .order("created_at", { ascending: false });
  },

  async addRepair(repair: {
    device_id: string;
    technician: string | null;
    issue: string;
    diagnosis: string | null;
    repair_notes: string | null;
    solution: string | null;
    priority: string;
    deposit: number;
    expected_completion_date: string | null;
    estimated_cost: number | null;
    final_cost: number | null;
    status: string;
  }) {
    return await supabase.from("repairs").insert([repair]);
  },

  async updateRepair(
    id: string,
    repair: {
      technician: string | null;
      issue: string;
      diagnosis: string | null;
      repair_notes: string | null;
      solution: string | null;
      priority: string;
      deposit: number;
      expected_completion_date: string | null;
      estimated_cost: number | null;
      final_cost: number | null;
      status: string;
    }
  ) {
    return await supabase.from("repairs").update(repair).eq("id", id);
  },

  async deleteRepair(id: string) {
    return await supabase.from("repairs").delete().eq("id", id);
  },

  // Marks a repair as Completed and issues a pickup ticket in one step.
  // The ticket_number is auto-generated by the database (NT-001, NT-002, ...).
  async completeRepair(id: string) {
    const { error: updateError } = await supabase
      .from("repairs")
      .update({
        status: "Completed",
        completed_at: new Date().toISOString(),
      })
      .eq("id", id);

    if (updateError) {
      return { data: null, error: updateError };
    }

    return await supabase
      .from("repair_tickets")
      .insert([{ repair_id: id }])
      .select()
      .single();
  },
};